function pairSlides(p){
  var k = p.key;
  return [
    {sec:'Представление и реальность', nav:'Угадайте · '+p.nav, center:true, blocks:[
      {t:'h1', v:'Угадайте, что это? 🤔'},
      {t:'p', v:'Пишите варианты в чат 👇'},
      {t:'shot', src:'photos/pairs/'+k+'-real.jpg', label:p.guessLabel||'Фото с диссекции'},
    ]},
    {sec:'Представление и реальность', nav:p.nav, blocks:[
      {t:'h1', v:p.title},
      {t:'pair', atlas:'photos/pairs/'+k+'-atlas.jpg', real:'photos/pairs/'+k+'-real.jpg',
        real2:p.real2?'photos/pairs/'+k+'-real2.jpg':undefined,
        labelA:p.labelA||'Фото из атласа', labelB:p.labelB||'Фото с диссекции'},
      {t:'p', v:p.atlas},
      {t:'p', v:p.real},
    ]},
  ];
}

